<?php

/**
 * drupilot — rector-compat.php
 * drupilot-template-version: 2
 *
 * The narrow compat pass (ADR 0002, ADR 0030). scripts/analysis/run-rector.sh
 * runs it right after the official pass, when the PHP window has a
 * deprecation fix the main pass does not run:
 *   vendor/bin/rector process web/modules/custom/legacy_widgets --config rector-compat.php
 * It registers only PHP deprecation fixes whose output still runs on the PHP
 * floor, and no set (so no polyfill rule either): the compat rows of
 * config/php/rules.json that are safe for Drupal, deprecated up to the top of
 * the window, and above the floor's level set (the upgrade plan's
 * rector.compat_rules, checked against the installed Rector's rule audit,
 * scripts/analysis/rector-rule-audit.sh). For example
 * ExplicitNullableParamTypeRector: `Foo $x = NULL` (an implicitly nullable
 * parameter, deprecated in PHP 8.4) becomes `?Foo $x = NULL`, valid since
 * PHP 7.1.
 * withPhpVersion() is the highest PHP version at which Rector's
 * PhpVersionedFilter keeps the listed rules (their provideMinPhpVersion()):
 * it raises nothing else. The rule list, not that filter, is what keeps the
 * output valid on the floor.
 *
 * Generated by scripts/env/render-templates.sh (or run-rector.sh when it is
 * missing or an untouched render for another plan or subject). Paths, skips
 * and file extensions are the same as in rector.php.
 */

declare(strict_types=1);

use Rector\Config\RectorConfig;
use Rector\ValueObject\PhpVersion;

// The same skip list as rector.php. String FQCNs + class_exists keep this
// config loadable on any Rector 2.x.
$drupilotRiskySkips = array_values(array_filter([
  'Rector\\Php83\\Rector\\FuncCall\\RemoveGetClassGetParentClassNoArgsRector',
  'Rector\\Php85\\Rector\\FuncCall\\OrdSingleByteRector',
  'Rector\\Php81\\Rector\\Array_\\ArrayToFirstClassCallableRector',
  'Rector\\Php83\\Rector\\ClassMethod\\AddOverrideAttributeToOverriddenMethodsRector',
  'Rector\\Php81\\Rector\\Property\\ReadOnlyPropertyRector',
  'Rector\\Php82\\Rector\\Class_\\ReadOnlyClassRector',
  'Rector\\Php81\\Rector\\FuncCall\\NullToStrictStringFuncCallArgRector',
  'Rector\\Php85\\Rector\\Class_\\SleepToSerializeRector',
  'Rector\\Php85\\Rector\\Class_\\WakeupToUnserializeRector',
  'Rector\\Php85\\Rector\\Property\\AddOverrideAttributeToOverriddenPropertiesRector',
  'Rector\\Php84\\Rector\\Class_\\DeprecatedAnnotationToDeprecatedAttributeRector',
  // The tests pass (ADR 0032): drupal-rector converts @group itself, and
  // keeps the annotation an older core of the range still reads.
  'Rector\\PHPUnit\\AnnotationsToAttributes\\Rector\\Class_\\AnnotationWithValueToAttributeRector',
], 'class_exists'));

// The compat rules (the plan's rector.compat_rules). An unknown class in
// withRules() is fatal too, so the list is filtered the same way.
$drupilotCompatRules = array_values(array_filter([
  'Rector\\Php84\\Rector\\Param\\ExplicitNullableParamTypeRector',
  'Rector\\Php84\\Rector\\FuncCall\\AddEscapeArgumentRector',
  'Rector\\Php85\\Rector\\ShellExec\\ShellExecFunctionCallOverBackticksRector',
  'Rector\\Php85\\Rector\\Switch_\\ColonAfterSwitchCaseRector',
  'Rector\\Php81\\Rector\\MethodCall\\RemoveReflectionSetAccessibleCallsRector',
  'Rector\\Php85\\Rector\\FuncCall\\ArrayKeyExistsNullToEmptyStringRector',
  'Rector\\Php85\\Rector\\ClassMethod\\NullDebugInfoReturnRector',
  'Rector\\Php85\\Rector\\FuncCall\\ChrArgModuloRector',
], 'class_exists'));

return RectorConfig::configure()
  ->withPaths([
    'web/modules/custom/legacy_widgets',
  ])
  ->withSkip(array_merge([
    '*/vendor/*',
    '*/node_modules/*',
  ], $drupilotRiskySkips))
  ->withPhpVersion(PhpVersion::PHP_85)
  ->withRules($drupilotCompatRules)
  ->withFileExtensions([
    'php',
    'module',
    'theme',
    'install',
    'inc',
    'profile',
    'engine',
  ]);
