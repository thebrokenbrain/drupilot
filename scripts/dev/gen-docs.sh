  TMP="$(mktemp -d "${TMPDIR:-/tmp}/drupilot-gendocs.XXXXXX")"
  trap 'rm -rf "$TMP"' EXIT
  generate "$TMP/out"
  DRIFT=""
  for p in $PAGES; do
    if ! cmp -s "$TMP/out/$p.md" "$OUT/$p.md"; then
      DRIFT="$DRIFT $p"
      diff -u "$OUT/$p.md" "$TMP/out/$p.md" 2>&1 | sed -n '1,40p' | sed 's/^/    /' >&2 || true
    fi
  done
  if [[ -n "$DRIFT" ]]; then log_err "gen-docs.sh: generated pages drift:$DRIFT (run scripts/dev/gen-docs.sh and commit)"
  else log_ok "gen-docs.sh: the generated reference pages are up to date"; fi
  if [[ "$AS_JSON" == "1" ]]; then
    jq -n -c --arg p "$PAGES" --arg d "$DRIFT" '{ok: ($d == ""), generated: ($p | split(" ") | map(. + ".md")), drift: ($d | split(" ") | map(select(. != "") | . + ".md"))}'
  fi
  [[ -z "$DRIFT" ]]; exit $?
fi
