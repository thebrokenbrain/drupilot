#!/usr/bin/env bash
# =============================================================================
# drupilot — scripts/analysis/php-lint-window.sh
# `php -l` on every PHP minor of the window W (T-M5-06, AR-03): one leg per
# minor, each in a throwaway official php CLI container (php_lint_docker: the
# image of config/php/versions.json, the tree streamed in, no network), so a
# module is compiled by the PHP it claims to run on, not only by the test-bed's.
# A leg records the compiler's messages per file:
#   parse-error, fatal-error  the file does not compile on that PHP: the leg
#                             fails
#   deprecated, warning, notice  compile-time messages (an implicitly nullable
#                             parameter on 8.4, ...): reported, never a failure
# W is --window, else the module's own frozen plan (php.window), else the PHP
# target alone. The PHP patch release each image ran is kept under meta (it
# changes with the image, not with the module: DET-2).
#
# Usage:
#   php-lint-window.sh --subject DIR [--window "X.Y X.Y ..."] [--json]
#                      [-h|--help]
#     --subject DIR    the module/theme
#     --window LIST    the PHP minors to lint (space- or comma-separated)
#     --json           {tool: "php-lint", window, status, legs: [{php, image,
#                     status, errors, deprecations, messages: [{kind, file,
#                     line, message}]}], meta: {php_versions}} on STDOUT
#
# status: pass (every leg ran and compiled), fail (a leg did not compile),
# skipped (every leg skipped: no Docker daemon, or no image could be pulled),
# error (no leg ran, and a run failed or timed out) or partial (some legs ran
# and compiled, others could not run). A leg is pass, fail, skipped or error.
#
# Exit codes: 0 linted (whatever the legs found; see status) · 1 usage error,
# an empty window, or a window minor that is not X.Y.
# =============================================================================
set -euo pipefail
# shellcheck source=../lib/common.sh
. "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"

SUBJECT=""; WINDOW=""; AS_JSON=0
usage() { print_usage "${BASH_SOURCE[0]}"; }
while [[ $# -gt 0 ]]; do
  case "$1" in
    --subject) SUBJECT="${2:-}"; shift 2 || die "--subject needs a value" 1;;
    --window) WINDOW="${2:-}"; shift 2 || die "--window needs a value" 1;;
    --json) AS_JSON=1; shift;;
    -h|--help) usage; exit 0;;
    *) die "Unknown argument: $1 (see --help)" 1;;
  esac
done
[[ -n "$SUBJECT" && -d "$SUBJECT" ]] || die "Pass --subject DIR (an existing directory)." 1
have_cmd jq || die "jq is required (run /drupilot-doctor)." 1
SUBJECT="$(cd "$SUBJECT" && pwd)"
[[ -n "$WINDOW" ]] || WINDOW="$(plan_get_own "$SUBJECT" '.php.window | join(" ")')"
[[ -n "$WINDOW" ]] || WINDOW="$(resolve_php_target)"
WINDOW="$(printf '%s' "$WINDOW" | tr ',' ' ')"
for v in $WINDOW; do
  [[ "$v" =~ ^[0-9]+\.[0-9]+$ ]] || die "A window minor is a PHP version X.Y (got '$v')." 1
done
[[ -n "$(printf '%s' "$WINDOW" | tr -d ' ')" ]] || die "The window holds no PHP version." 1
TMP="$(mktemp -d "${TMPDIR:-/tmp}/drupilot-php-lint.XXXXXX")"
trap 'rm -rf "$TMP" 2> /dev/null || true' EXIT

# The in-container helper (POSIX sh, the image's GNU tools): "V<TAB>version",
# then "M<TAB>kind<TAB>file<TAB>line<TAB>message" per compiler message, and
# "X<TAB>file<TAB>rc" for a file php -l rejected.
cat > "$TMP/lint.sh" <<'LINT'
#!/bin/sh
# drupilot — php -l over a module tree, every compiler message (generated by php-lint-window.sh).
cd "${1:-.}" || exit 2
printf 'V\t%s\n' "$(php -r 'echo PHP_VERSION;')"
find . \( -name .git -o -name vendor -o -name node_modules \) -prune -o -type f \
  \( -name '*.php' -o -name '*.module' -o -name '*.inc' -o -name '*.install' \
     -o -name '*.theme' -o -name '*.profile' -o -name '*.engine' \) -print | LC_ALL=C sort |
while IFS= read -r f; do
  out="$(php -d display_errors=1 -d log_errors=0 -d html_errors=0 -d error_reporting=-1 -l "$f" 2>&1)"
  rc=$?
  # Each "<Kind>: <message> in <f> on line <N>" line, cut at the file php -l
  # was given (a path may itself contain " in ").
  printf '%s\n' "$out" | PHPL_FILE="$f" awk '{
    f = ENVIRON["PHPL_FILE"]; pat = " in " f " on line "; p = index($0, pat); if (p == 0) next
    n = substr($0, p + length(pat)); if (n !~ /^[0-9]+$/) next
    m = substr($0, 1, p - 1); sub(/^PHP /, "", m); q = index(m, ": "); if (q == 0) next
    k = substr(m, 1, q - 1); if (k !~ /^[A-Z][A-Za-z ]*$/) next
    msg = substr(m, q + 2); sub(/^ +/, "", msg)
    printf "M\t%s\t%s\t%s\t%s\n", k, f, n, msg }'
  [ "$rc" -eq 0 ] || printf 'X\t%s\t%s\n' "$f" "$rc"
done
exit 0
LINT

LEGS="$TMP/legs.jsonl"; : > "$LEGS"
for v in $WINDOW; do
  log_step "php -l on PHP $v"
  st="$(php_lint_docker "$v" "$SUBJECT" "$TMP/lint.sh" "$TMP/lint-$v.tsv")"
  jq -R -s -c --arg php "$v" --arg img "$(php_cli_image "$v")" --arg st "$st" '
    def kind: ascii_downcase | gsub(" "; "-");
    def rel: sub("^\\./"; "");
    split("\n") | map(select(length > 0) | split("\t")) as $rows
    | ([$rows[] | select(.[0] == "M" and length >= 5)
        | {kind: (.[1] | kind), file: (.[2] | rel), line: (.[3] | tonumber? // null), message: (.[4:] | join("\t"))}]
       | unique_by([.file, .line, .kind, .message]) | sort_by([.file, (.line // 0), .kind, .message])) as $m
    | ([$m[] | select(.kind == "parse-error" or .kind == "fatal-error") | .file] | unique) as $ef
    # A file php -l rejected without a message the helper could read.
    | ([$rows[] | select(.[0] == "X") | .[1] | rel] | unique | map(select(. as $f | $ef | index($f) | not))) as $bare
    | ($m + [$bare[] | {kind: "lint-error", file: ., line: null, message: "php -l rejected the file"}]) as $all
    | ([$all[] | select(.kind == "parse-error" or .kind == "fatal-error" or .kind == "lint-error")] | length) as $e
    | {php: $php, image: $img,
       status: (if $st != "ran" then $st elif $e > 0 then "fail" else "pass" end),
       errors: $e, deprecations: ([$all[] | select(.kind == "deprecated")] | length),
       messages: (if $st == "ran" then $all else [] end),
       version: ([$rows[] | select(.[0] == "V") | .[1]] | .[0] // null)}' "$TMP/lint-$v.tsv" >> "$LEGS"
done
OUT="$(jq -s -c --arg w "$WINDOW" '
  {tool: "php-lint", window: ($w | split(" ") | map(select(length > 0))),
   status: (if any(.[]; .status == "fail") then "fail"
            elif all(.[]; .status == "pass") then "pass"
            elif all(.[]; .status == "skipped") then "skipped"
            elif any(.[]; .status == "pass") then "partial"
            else "error" end),
   legs: map(del(.version)),
   meta: {php_versions: (map(select(.version != null) | {key: .php, value: .version}) | from_entries)}}' "$LEGS")"
if [[ "$AS_JSON" == "1" ]]; then
  printf '%s\n' "$OUT" | canon_json
else
  printf '%s\n' "$OUT" | jq -r '.legs[] | "PHP \(.php): \(.status) (\(.errors) error(s), \(.deprecations) deprecation(s))",
    (.messages[] | "  \(.kind)\t\(.file):\(.line // "-")\t\(.message)")'
fi
log_info "php-lint: window $(printf '%s' "$WINDOW" | tr ' ' ','): $(jq -r '.status' <<< "$OUT")."
exit 0
